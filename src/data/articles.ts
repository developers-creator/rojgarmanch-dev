function buildArticleDeck(excerpt?: string): string {
  const base =
    excerpt?.trim() ||
    "यो विषयका मुख्य घटना, सन्दर्भ र प्रभावलाई हामीले विस्तृत रूपमा समेटेका छौं।";
  const bridge =
    " यस विषयले युवा, कामदार र नीति निर्माताहरूको दैनिक निर्णयलाई असर पार्न सक्ने भएकाले सन्दर्भसहित बुझ्नु महत्त्वपूर्ण छ।";

  if (base.includes("सन्दर्भसहित बुझ्नु")) return base;

  const normalized = /।\s*$/.test(base) ? base.replace(/\s+$/, "") : `${base}।`;
  return `${normalized}${bridge}`;
}

