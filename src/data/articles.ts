function allPosts(): Post[] {
  const home = getHomePageData();
  const fromCategories = getAllCategorySlugs().flatMap((slug) =>
    getCategoryPosts(slug),
  );
  return [
    home.highlight,
    ...home.highlightMore,
    home.feature,
    ...home.featurePair,
    ...home.teasers,
    ...home.recent,
    ...home.stories,
    ...fromCategories,
  ];
}

export function getAllArticleSlugs(): string[] {
  const slugs = new Set<string>([
    ...Object.keys(articles),
    ...allPosts().map((p) => p.slug).filter(Boolean),
  ]);
  return [...slugs];
}

export function getArticle(slug: string): Article | null {
  const rich = articles[slug];
  if (rich) {
    return { ...rich, href: `/article/${rich.slug}` };
  }

  const match = allPosts().find((p) => p.slug === slug);
  if (!match) return null;
  return buildFallback(match);
}

export function getRelatedArticles(
  slug: string,
  limit = 3,
): Pick<
  Post,
  "title" | "href" | "imageUrl" | "imageAlt" | "category" | "dateLabel" | "excerpt"
>[] {
  const seen = new Set<string>();
  const related: Pick<
    Post,
    "title" | "href" | "imageUrl" | "imageAlt" | "category" | "dateLabel" | "excerpt"
  >[] = [];

  for (const post of allPosts()) {
    if (!post.slug || post.slug === slug || seen.has(post.slug)) continue;
    seen.add(post.slug);
    related.push({
      title: post.title,
      href: post.href.startsWith("/article/")
        ? post.href
        : `/article/${post.slug}`,
      imageUrl: post.imageUrl || u("1507679799987-c73779587ccf", 640, 400),
      imageAlt: post.imageAlt || post.title,
      category: post.category,
      dateLabel: post.dateLabel,
      excerpt: post.excerpt,
    });
    if (related.length >= limit) break;
  }

  return related;
}
